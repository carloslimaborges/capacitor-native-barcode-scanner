package com.github.carloslimaborges.barcodescanner;

import com.getcapacitor.JSObject;
import com.getcapacitor.Plugin;
import com.getcapacitor.PluginCall;
import com.getcapacitor.PluginMethod;
import com.getcapacitor.annotation.CapacitorPlugin;

@CapacitorPlugin(name = "MpdftBarcodeScannerPlugin")
public class MpdftBarcodeScannerPluginPlugin extends Plugin {

    private MpdftBarcodeScannerPlugin implementation = new MpdftBarcodeScannerPlugin();

    @PluginMethod
    public void echo(PluginCall call) {
        String value = call.getString("value");

        JSObject ret = new JSObject();
        ret.put("value", implementation.echo(value));
        call.resolve(ret);
    }
}
